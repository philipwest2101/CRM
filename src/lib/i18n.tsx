export type Lang = "en" | "de";
export type TKey = keyof typeof TRANSLATIONS.en;

export const LangContext = React.createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

export const useT = () => {
  const { lang } = useContext(LangContext);
  return (key: TKey, fallback?: string): string => {
    return (TRANSLATIONS[lang] as any)[key] ?? (TRANSLATIONS.en as any)[key] ?? fallback ?? key;
  };
};
